"""Generate the exponential table behind the native complete-input KBDI path.

Writes ``crates/climate-indices/src/kbdi_exp_table.rs``: ``2^(j/256)`` for ``j`` in
``0..256``, each correctly rounded to float64 (computed with 60 significant
digits), and the heat-term offset ``1.5552 + ln 0.968``. Standard library only;
run from the repository root::

    python scripts/generate_kbdi_exp_table.py
"""

from __future__ import annotations

import struct
from decimal import Decimal, getcontext
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "crates" / "climate-indices" / "src" / "kbdi_exp_table.rs"


def _bits(value: Decimal) -> str:
    """The float64 nearest ``value`` as a Rust hexadecimal bit-pattern literal."""
    (word,) = struct.unpack("<Q", struct.pack("<d", float(value)))
    return f"0x{word:016x}"


def main() -> None:
    getcontext().prec = 60
    ln2 = Decimal(2).ln()
    rows = "\n".join(f"    {_bits((ln2 * j / 256).exp())}," for j in range(256))
    offset = float(Decimal("1.5552") + Decimal("0.968").ln())
    TARGET.write_text(
        "//! Generated by `scripts/generate_kbdi_exp_table.py`; do not edit.\n"
        "//!\n"
        "//! `2^(j/256)` for `j` in `0..256`, each correctly rounded to f64, as bit\n"
        "//! patterns, and the heat-term offset of `crate::kbdi_fast::heat`.\n"
        "\n"
        "pub(crate) const EXP2_TABLE_BITS: [u64; 256] = [\n"
        f"{rows}\n"
        "];\n"
        "\n"
        "/// `1.5552 + ln 0.968`, so `exp(0.0875 T + HEAT_OFFSET) = 0.968 exp(0.0875 T + 1.5552)`.\n"
        f"pub(crate) const HEAT_OFFSET: f64 = {offset!r};\n",
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    main()
