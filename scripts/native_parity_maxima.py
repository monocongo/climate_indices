"""Measure cross-backend parity per registered kernel and print the tolerance table.

The table is the evidence for the parity section of ``docs/architecture.md``: one
row per entry in ``tests/parity_registry.py``, with the largest absolute and
relative deviation measured on this platform. CI's native leg appends the table to
its job summary, so the same measurement is recorded on Linux x86-64 as well as on
a developer's macOS arm64 machine.

Usage: ``uv run python scripts/native_parity_maxima.py`` with the extension built
(``uv run maturin develop --release``).
"""

from __future__ import annotations

import argparse
import platform
import subprocess
import sys
from collections.abc import Mapping
from pathlib import Path

import numpy as np
import pytest
import scipy
from scipy import special

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tests import parity_registry  # noqa: E402 - the repository root has to be importable first


def measured_platform() -> str:
    """The platform the maxima below were measured on."""
    machine = platform.machine()
    system = platform.system()
    return f"{system} {machine} ({platform.python_implementation()} {platform.python_version()})"


SPECIAL_NAMES = frozenset({"special_igam", "special_igamc", "special_ndtri", "special_norm_ppf", "special_ndtr"})

# The documented corpus of `crates/climate-core/examples/special_accuracy.rs`: each
# name maps to its total probe count and the number of probes whose SciPy reference
# is finite. Changing that example must update this table (and the report text), so
# a truncated, duplicated, or swapped probe set cannot pass as measured evidence.
PROBE_CORPUS = {
    "special_igam": (196, 167),
    "special_igamc": (196, 167),
    "special_ndtri": (12, 6),
    "special_norm_ppf": (12, 6),
    "special_ndtr": (11, 10),
}


def special_errors(output: str, corpus: Mapping[str, tuple[int, int]] | None = None) -> dict[str, tuple[float, float]]:
    """Compare the Rust scalar probes with SciPy, rejecting missing or invalid evidence."""
    corpus = PROBE_CORPUS if corpus is None else corpus
    pairs: dict[str, list[tuple[float, float]]] = {name: [] for name in SPECIAL_NAMES}
    seen: set[tuple[str, str, str]] = set()
    for line in output.splitlines():
        name, a_text, x_text, actual_text = line.split(",")
        if (name, a_text, x_text) in seen:
            raise ValueError(f"Duplicate scalar probe: {name} at {a_text}, {x_text}")
        seen.add((name, a_text, x_text))
        a, x, actual = float(a_text), float(x_text), float(actual_text)
        if name == "special_igam":
            expected = special.gammainc(a, x)
        elif name == "special_igamc":
            expected = special.gammaincc(a, x)
        elif name in {"special_ndtri", "special_norm_ppf"}:
            expected = special.ndtri(a)
        elif name == "special_ndtr":
            expected = special.ndtr(a)
        else:
            raise ValueError(f"Unknown scalar probe: {name}")
        pairs[name].append((actual, float(expected)))
    errors = {}
    for name, values in sorted(pairs.items()):
        if not values:
            raise ValueError(f"Missing scalar probes: {name}")
        total_probes, finite_floor = corpus[name]
        if len(values) != total_probes:
            raise ValueError(f"Wrong scalar probe count: {name} has {len(values)}, needs {total_probes}")
        actual, expected = np.asarray(values).T
        np.testing.assert_allclose(
            actual, expected, rtol=parity_registry.RTOL, atol=parity_registry.ATOL, equal_nan=True
        )
        finite = int(np.count_nonzero(np.isfinite(expected)))
        if finite < finite_floor:
            raise ValueError(f"Too few finite scalar probes: {name} has {finite}, needs {finite_floor}")
        errors[name] = parity_registry.parity_errors(actual, expected)
    return errors


def contract_report(runs: list[parity_registry.ParityRun], scalar_errors: dict[str, tuple[float, float]]) -> str:
    """Render the shared rustdoc/Sphinx accuracy page from measured values only."""
    lines = [
        "# Measured accuracy",
        "",
        "<!-- Generated by scripts/native_parity_maxima.py --write-contract. -->",
        "",
        f"Measured on {measured_platform()}, NumPy {np.__version__}, SciPy {scipy.__version__}.",
        "The values describe this deterministic corpus, not universal error bounds or independent scientific validation.",
        "No algorithm, physical-range validation, or calendar preparation changes in this contract.",
        "",
        "## Workflow measurements",
        "",
        "Each row compares a complete workflow against the Python/SciPy reference with native dispatch disabled.",
        "The harness verifies that the listed Rust kernels actually ran.",
        "A workflow error is not an isolated error bound for each kernel it uses.",
        "The numerical contracts on each function identify the applicable rows.",
        "",
        "The corpus comes from `tests/parity_registry.py::SAMPLES`, with fixed seeds 20261009, 20261010, and 20261011.",
        "It contains 35 monthly years, five 365-day daily years, and a 35-year monthly Spatial Block with three cells.",
        "The samples include zeros, NaNs, and extreme precipitation; entry-specific derivations prepare each kernel's inputs.",
        "Palmer replaces gaps and clips precipitation to [5, 300] in the inch-based water-balance inputs.",
        "Monthly fitting starts in 1981 and uses the interior Calibration Period; daily flood entries prepare an all-leap calendar.",
        "The registry records the exact derivations and parameters.",
        "",
        "| Entry | Rust kernels reached | Max absolute | Max relative |",
        "| --- | --- | --- | --- |",
    ]
    for run in sorted(runs, key=lambda item: item.entry.name):
        kernels = ", ".join(f"`{name}`" for name in sorted(run.calls))
        if parity_registry.compared_pairs(run.rust, run.python):
            errors = f"{run.max_absolute:.6e} | {run.max_relative:.6e}"
        else:
            errors = "no finite comparison | no finite comparison"
        lines.append(f"| `{run.entry.name}` | {kernels} | {errors} |")
    vacuous = [run.entry.name for run in runs if not parity_registry.compared_pairs(run.rust, run.python)]
    if vacuous:
        names = ", ".join(f"`{name}`" for name in sorted(vacuous))
        lines.extend(
            [
                "",
                f"These entries have no finite comparison on this corpus: {names}.",
                "Their samples poison every recorded value, so those rows record NaN-position parity only, not a numeric error.",
            ]
        )
    lines.extend(
        [
            "",
            "## Direct special-function measurements",
            "",
            "`crates/climate-core/examples/special_accuracy.rs` prints scalar results for direct comparison with SciPy.",
            "Gamma probes cross 14 shape values with 14 argument values from zero through 1e6, infinity, and NaN.",
            "Quantile probes include 1e-300, central probabilities, both endpoints, and invalid inputs.",
            "Normal-CDF probes include both tails through +/-40, zero, infinities, and NaN.",
            "These rows measure the named scalar function, without an index workflow.",
            "The corpus has 427 probes: 196 per gamma function, 12 per quantile function, and 11 normal-CDF probes.",
            "The generator rejects a truncated, duplicated, or count-mismatched probe set.",
            "",
            "| Entry | Max absolute | Max relative |",
            "| --- | --- | --- |",
        ]
    )
    for name, (absolute, relative) in sorted(scalar_errors.items()):
        lines.append(f"| `{name}` | {absolute:.6e} | {relative:.6e} |")
    lines.extend(
        [
            "",
            "## Interpretation and reproduction",
            "",
            "Absolute error is `abs(rust - reference)`; relative error divides that error by `abs(reference)` for nonzero references.",
            "Zero references contribute only to absolute error. Matching NaNs and matching signed infinities do not contribute to maxima.",
            "The tests check NaN positions and infinity signs separately through the parity comparator.",
            "Every comparison must satisfy `rtol = atol = 1e-10`; those tolerances are acceptance criteria, not measured errors.",
            "A reported relative error can exceed the relative tolerance when the absolute tolerance governs a value near zero.",
            "State-plumbing helpers copy or index values and have no independent arithmetic accuracy claim.",
            "Rust-only verification coverage and independent reference fixtures remain separate from these workflow measurements.",
            "",
            "From the repository root, build the extension and regenerate this page:",
            "",
            "```bash",
            "uv run maturin develop --release",
            "uv run python scripts/native_parity_maxima.py --write-contract",
            "```",
            "",
            "The second command also runs `cargo run -p climate-core --example special_accuracy --quiet`.",
            "Run `uv run pytest tests/test_native_parity_registry.py` to exercise the same deterministic workflow comparisons and property draws.",
            "Cross-platform differences can change the maxima. Regenerate the page only after reviewing those differences.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write-contract", action="store_true", help="Regenerate the crate's NUMERICS.md accuracy page."
    )
    args = parser.parse_args()
    monkeypatch = pytest.MonkeyPatch()
    try:
        runs = parity_registry.measure(monkeypatch)
    finally:
        monkeypatch.undo()

    if args.write_contract:
        probes = subprocess.run(
            ["cargo", "run", "-p", "climate-core", "--example", "special_accuracy", "--quiet"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        )
        report = contract_report(runs, special_errors(probes.stdout))
        (ROOT / "crates/climate-core/NUMERICS.md").write_text(report, encoding="utf-8")

    print(f"Parity maxima measured on {measured_platform()}.")
    print()
    print("| Entry | Kernels | Max absolute | Max relative |")
    print("| --- | --- | --- | --- |")
    for run in sorted(runs, key=lambda item: item.entry.name):
        kernels = ", ".join(f"`{name}`" for name in sorted(run.calls))
        if parity_registry.compared_pairs(run.rust, run.python):
            errors = f"{run.max_absolute:.3e} | {run.max_relative:.3e}"
        else:
            errors = "no finite comparison | no finite comparison"
        print(f"| `{run.entry.name}` | {kernels} | {errors} |")
    print()
    worst = max(runs, key=lambda item: item.max_absolute)
    print(
        f"The largest absolute deviation is {worst.max_absolute:.3e} ({worst.entry.name}); "
        f"every entry is compared at rtol = atol = {parity_registry.RTOL:.0e} with matching NaN positions."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
